#!/bin/bash
# ==============================================================================
# run_interactive.sh — Запуск интерактивного тестирования X-UI в Docker
# ==============================================================================
set -e

DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$DIR"

echo "=========================================================="
echo "  Сборка тестового Docker-образа (xui-test)..."
echo "=========================================================="
docker build -f Dockerfile.test -t xui-test .

echo ""
echo "=========================================================="
echo "  Запуск интерактивного контейнера..."
echo "  Проброс портов: 127.0.0.1:8443->443 (HTTPS), 127.0.0.1:8080->80 (HTTP)"
echo "=========================================================="
docker run -it --rm \
    -p 127.0.0.1:8443:443 \
    -p 127.0.0.1:8080:80 \
    --name xui-interactive \
    xui-test \
    /interactive_test.sh
